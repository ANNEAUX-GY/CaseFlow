def _cw(ch):
    o = ord(ch)
    if o > 0x2E80:
        return 1.0
    if ch == ' ':
        return 0.32
    if ch in '·—→←（）()、，。：；「」『』':
        return 0.6
    return 0.52


def need_h(items, box_w):
    total = 0.0
    for text, size, ls, sa in items:
        size_px = size * 96.0 / 72.0
        per_line = max(1.0, box_w / size_px)
        wsum = sum(_cw(c) for c in text)
        lines = int(wsum / per_line) + (1 if wsum % per_line > 0.01 else 0)
        total += lines * size_px * ls * 1.34 + sa * 96.0 / 72.0
    return total


